def colore_testo_hud(rgb, verso_bianco=0.34):
    """Schiarisce un colore cellula per leggerlo sul pannello HUD."""
    r, g, b = rgb[:3]
    t = max(0.0, min(1.0, verso_bianco))
    return (
        min(255, int(r + (255 - r) * t)),
        min(255, int(g + (255 - g) * t)),
        min(255, int(b + (255 - b) * t)),
    )


